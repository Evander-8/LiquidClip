import Foundation
import AppKit

@MainActor
public class ClipboardMonitor {
    public static let shared = ClipboardMonitor()
    
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int = 0
    private var timer: Timer?
    public var isSelfCopying: Bool = false
    private var globalKeyMonitor: Any?
    private var globalMouseMonitor: Any?
    public var lastExplicitCopyTime: Date = Date.distantPast
    
    // Concealed pasteboard types used by password managers (1Password, Bitwarden, etc.)
    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.dstoecker.xfreecell.concealed"),
        NSPasteboard.PasteboardType("application/x-nspasteboard-concealed-type")
    ]
    
    private init() {
        self.lastChangeCount = pasteboard.changeCount
    }
    
    public func startMonitoring() {
        self.lastChangeCount = pasteboard.changeCount
        // Poll every 0.3 seconds on main runloop
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
        RunLoop.current.add(timer!, forMode: .common)
        
        // Track global Command+C keydown to distinguish explicit copy vs automatic copy-on-select
        globalKeyMonitor = NSEvent.addGlobalMonitorForEvents(matching: .keyDown) { [weak self] event in
            if event.modifierFlags.contains(.command) && event.charactersIgnoringModifiers?.lowercased() == "c" {
                Task { @MainActor [weak self] in
                    self?.lastExplicitCopyTime = Date()
                }
            }
        }
        
        setupMouseSelectionMonitor()
    }
    
    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
        if let keyMon = globalKeyMonitor {
            NSEvent.removeMonitor(keyMon)
            globalKeyMonitor = nil
        }
        if let mouseMon = globalMouseMonitor {
            NSEvent.removeMonitor(mouseMon)
            globalMouseMonitor = nil
        }
    }
    
    // Toggle active system-wide selection copy
    public func setupMouseSelectionMonitor() {
        if let existing = globalMouseMonitor {
            NSEvent.removeMonitor(existing)
            globalMouseMonitor = nil
        }
        
        guard AppSettings.shared.enableSelectionCopy else { return }
        
        globalMouseMonitor = NSEvent.addGlobalMonitorForEvents(matching: .leftMouseUp) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.handleGlobalMouseUp()
            }
        }
    }
    
    private func handleGlobalMouseUp() {
        guard AppSettings.shared.enableSelectionCopy else { return }
        guard PasteSimulator.shared.isAccessibilityTrusted else { return }
        
        let frontApp = NSWorkspace.shared.frontmostApplication
        if frontApp?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        
        // Query selected text from frontmost focused element
        let systemWide = AXUIElementCreateSystemWide()
        var focusedAppRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedApplicationAttribute as CFString, &focusedAppRef) == .success,
              let focusedApp = focusedAppRef else { return }
        
        var focusedElemRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focusedApp as! AXUIElement, kAXFocusedUIElementAttribute as CFString, &focusedElemRef) == .success,
              let focusedElem = focusedElemRef else { return }
        
        var selectedTextRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(focusedElem as! AXUIElement, kAXSelectedTextAttribute as CFString, &selectedTextRef) == .success,
           let text = selectedTextRef as? String {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty && trimmed != NSPasteboard.general.string(forType: .string) {
                lastExplicitCopyTime = Date()
                NSPasteboard.general.clearContents()
                NSPasteboard.general.setString(text, forType: .string)
            }
        }
    }
    
    // Synchronize changeCount immediately to prevent self-triggered copy events from firing
    public func syncChangeCount() {
        self.lastChangeCount = pasteboard.changeCount
        self.isSelfCopying = false
    }
    
    private func checkPasteboard() {
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount
        
        // If this copy was initiated by LiquidClip itself (e.g. during paste action), skip reprocessing
        if isSelfCopying {
            isSelfCopying = false
            return
        }
        
        // Check for concealed/private data
        if AppSettings.shared.ignorePasswordManagers {
            if let types = pasteboard.types {
                for concealed in concealedTypes {
                    if types.contains(concealed) {
                        return
                    }
                }
            }
        }
        
        // Get source application
        let frontApp = NSWorkspace.shared.frontmostApplication
        let bundleId = frontApp?.bundleIdentifier ?? ""
        let appName = frontApp?.localizedName ?? "系统"
        
        // Excluded applications check
        if AppSettings.shared.excludedApps.contains(where: { bundleId.localizedCaseInsensitiveContains($0) }) {
            return
        }
        
        // Terminal applications that perform automatic copy-on-select
        let terminalApps = [
            "com.mitchellh.ghostty",
            "com.googlecode.iterm2",
            "com.apple.Terminal",
            "io.alacritty",
            "dev.warp.Warp-Stable",
            "net.kovidgoyal.kitty"
        ]
        
        // When selection copy is disabled, ignore terminal swipe-to-copy unless Command+C was pressed
        if !AppSettings.shared.enableSelectionCopy {
            let isTerminal = terminalApps.contains(where: { bundleId.localizedCaseInsensitiveContains($0) })
            if isTerminal {
                let timeSinceCmdC = Date().timeIntervalSince(lastExplicitCopyTime)
                if timeSinceCmdC > 1.2 {
                    // Automatic swipe selection without Command+C; ignore!
                    return
                }
            }
        }
        
        processCurrentPasteboard(sourceAppName: appName, sourceBundleId: bundleId)
    }
    
    private func processCurrentPasteboard(sourceAppName: String, sourceBundleId: String) {
        // 1. Check for File URLs first
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [
            NSPasteboard.ReadingOptionKey.urlReadingFileURLsOnly: true
        ]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path }
            
            // If it is a single image file (common in WeChat, Finder, etc.), save as .image
            let imageExtensions = ["png", "jpg", "jpeg", "webp", "gif", "tiff", "tif", "heic", "heif", "svg", "bmp"]
            if paths.count == 1,
               let first = paths.first,
               imageExtensions.contains((first as NSString).pathExtension.lowercased()),
               let img = NSImage(contentsOfFile: first),
               let saved = StorageManager.shared.saveImage(img) {
                let item = ClipItem(
                    type: .image,
                    imageFileName: saved.fileName,
                    imageWidth: saved.width,
                    imageHeight: saved.height,
                    filePaths: paths,
                    sourceAppName: sourceAppName,
                    sourceAppBundleId: sourceBundleId
                )
                StorageManager.shared.addClip(item)
                return
            }
            
            let item = ClipItem(
                type: .file,
                filePaths: paths,
                sourceAppName: sourceAppName,
                sourceAppBundleId: sourceBundleId
            )
            StorageManager.shared.addClip(item)
            return
        }
        
        // 2. Check for Images
        if let types = pasteboard.types,
           types.contains(.png) || types.contains(.tiff),
           let img = NSImage(pasteboard: pasteboard) {
            if img.size.width > 2 && img.size.height > 2 {
                if let saved = StorageManager.shared.saveImage(img) {
                    let item = ClipItem(
                        type: .image,
                        imageFileName: saved.fileName,
                        imageWidth: saved.width,
                        imageHeight: saved.height,
                        sourceAppName: sourceAppName,
                        sourceAppBundleId: sourceBundleId
                    )
                    StorageManager.shared.addClip(item)
                    return
                }
            }
        }
        
        // 3. Check for Strings
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let html = pasteboard.string(forType: .html)
            
            // Check if it is a Color code
            if let colorHex = extractColorHex(from: trimmed) {
                let item = ClipItem(
                    type: .color,
                    plainText: trimmed,
                    htmlText: html,
                    colorHex: colorHex,
                    sourceAppName: sourceAppName,
                    sourceAppBundleId: sourceBundleId
                )
                StorageManager.shared.addClip(item)
                return
            }
            
            // Check if it is a Web URL
            if isValidWebURL(trimmed) {
                let item = ClipItem(
                    type: .url,
                    plainText: trimmed,
                    htmlText: html,
                    sourceAppName: sourceAppName,
                    sourceAppBundleId: sourceBundleId
                )
                StorageManager.shared.addClip(item)
                return
            }
            
            // Regular Text
            let item = ClipItem(
                type: .text,
                plainText: string,
                htmlText: html,
                sourceAppName: sourceAppName,
                sourceAppBundleId: sourceBundleId
            )
            StorageManager.shared.addClip(item)
        }
    }
    
    // Extract Hex Color
    private func extractColorHex(from text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        
        let hexRegex = "^#?([A-Fa-f0-9]{6}|[A-Fa-f0-9]{8}|[A-Fa-f0-9]{3})$"
        if trimmed.range(of: hexRegex, options: .regularExpression) != nil {
            return trimmed.hasPrefix("#") ? trimmed.uppercased() : "#\(trimmed.uppercased())"
        }
        
        let rgbRegex = "^rgb\\s*\\(\\s*(\\d{1,3})\\s*,\\s*(\\d{1,3})\\s*,\\s*(\\d{1,3})\\s*\\)$"
        if let regex = try? NSRegularExpression(pattern: rgbRegex, options: .caseInsensitive) {
            let nsString = trimmed as NSString
            if let match = regex.firstMatch(in: trimmed, options: [], range: NSRange(location: 0, length: nsString.length)) {
                if match.numberOfRanges == 4 {
                    let r = Int(nsString.substring(with: match.range(at: 1))) ?? 0
                    let g = Int(nsString.substring(with: match.range(at: 2))) ?? 0
                    let b = Int(nsString.substring(with: match.range(at: 3))) ?? 0
                    if r <= 255 && g <= 255 && b <= 255 {
                        return String(format: "#%02X%02X%02X", r, g, b)
                    }
                }
            }
        }
        
        return nil
    }
    
    // Check if string is a valid web URL
    private func isValidWebURL(_ string: String) -> Bool {
        guard !string.contains("\n") && !string.contains(" ") else { return false }
        if let url = URL(string: string), let scheme = url.scheme?.lowercased() {
            if (scheme == "http" || scheme == "https") && url.host != nil && !url.host!.isEmpty {
                return true
            }
        }
        return false
    }
}
