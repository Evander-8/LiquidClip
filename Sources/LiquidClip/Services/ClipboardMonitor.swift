/**
 * [INPUT]: 依赖 NSPasteboard、NSWorkspace、AppSettings、PasteSimulator 与 StorageManager 异步入库接口
 * [OUTPUT]: 提供全局单例 ClipboardMonitor，监听系统剪贴板变化与划词复制，过滤隐私/瞬态类型与排除应用后分类入库（含严格色彩识别）
 * [POS]: 剪贴板采集引擎，在后台持续运行并将标准化的 ClipItem 或异步图像任务交付 StorageManager
 * [PROTOCOL]: Update this header on change, then check GEMINI.md
 */

import Foundation
import AppKit

@MainActor
public class ClipboardMonitor {
    public static let shared = ClipboardMonitor()
    
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int = 0
    private var timer: Timer?
    public var isSelfCopying: Bool = false
    private var globalKeyMonitor: Any?
    private var globalMouseMonitor: Any?
    public var lastExplicitCopyTime: Date = Date.distantPast
    
    // Concealed and transient pasteboard types used by password managers and macOS utilities
    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.dstoecker.xfreecell.concealed"),
        NSPasteboard.PasteboardType("application/x-nspasteboard-concealed-type")
    ]
    
    private init() {
        self.lastChangeCount = pasteboard.changeCount
    }
    
    public func startMonitoring() {
        self.lastChangeCount = pasteboard.changeCount
        // Poll every 0.4 seconds with tolerance to allow macOS timer coalescing
        let pollTimer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
        pollTimer.tolerance = 0.1
        self.timer = pollTimer
        RunLoop.current.add(pollTimer, forMode: .common)
        
        // Track global Command+C keydown to distinguish explicit copy vs automatic copy-on-select
        globalKeyMonitor = NSEvent.addGlobalMonitorForEvents(matching: .keyDown) { [weak self] event in
            if event.modifierFlags.contains(.command) && event.charactersIgnoringModifiers?.lowercased() == "c" {
                Task { @MainActor [weak self] in
                    self?.lastExplicitCopyTime = Date()
                }
            }
        }
        
        setupMouseSelectionMonitor()
    }
    
    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
        if let keyMon = globalKeyMonitor {
            NSEvent.removeMonitor(keyMon)
            globalKeyMonitor = nil
        }
        if let mouseMon = globalMouseMonitor {
            NSEvent.removeMonitor(mouseMon)
            globalMouseMonitor = nil
        }
    }
    
    // Toggle active system-wide selection copy
    public func setupMouseSelectionMonitor() {
        if let existing = globalMouseMonitor {
            NSEvent.removeMonitor(existing)
            globalMouseMonitor = nil
        }
        
        guard AppSettings.shared.enableSelectionCopy else { return }
        
        globalMouseMonitor = NSEvent.addGlobalMonitorForEvents(matching: .leftMouseUp) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.handleGlobalMouseUp()
            }
        }
    }
    
    private func handleGlobalMouseUp() {
        guard AppSettings.shared.enableSelectionCopy else { return }
        guard PasteSimulator.shared.isAccessibilityTrusted else { return }
        
        let frontApp = NSWorkspace.shared.frontmostApplication
        if frontApp?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        
        // Query selected text from frontmost focused element
        let systemWide = AXUIElementCreateSystemWide()
        var focusedAppRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedApplicationAttribute as CFString, &focusedAppRef) == .success,
              let focusedApp = focusedAppRef else { return }
        
        var focusedElemRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focusedApp as! AXUIElement, kAXFocusedUIElementAttribute as CFString, &focusedElemRef) == .success,
              let focusedElem = focusedElemRef else { return }
        
        var selectedTextRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(focusedElem as! AXUIElement, kAXSelectedTextAttribute as CFString, &selectedTextRef) == .success,
           let text = selectedTextRef as? String {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty && trimmed != NSPasteboard.general.string(forType: .string) {
                lastExplicitCopyTime = Date()
                NSPasteboard.general.clearContents()
                NSPasteboard.general.setString(text, forType: .string)
            }
        }
    }
    
    // Synchronize changeCount immediately to prevent self-triggered copy events from firing
    public func syncChangeCount() {
        self.lastChangeCount = pasteboard.changeCount
        self.isSelfCopying = false
    }
    
    private func checkPasteboard() {
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount
        
        // If this copy was initiated by LiquidClip itself (e.g. during paste action), skip reprocessing
        if isSelfCopying {
            isSelfCopying = false
            return
        }
        
        // Check for concealed/private data
        if AppSettings.shared.ignorePasswordManagers {
            if let types = pasteboard.types {
                for concealed in concealedTypes {
                    if types.contains(concealed) {
                        return
                    }
                }
            }
        }
        
        // Get source application
        let frontApp = NSWorkspace.shared.frontmostApplication
        let bundleId = frontApp?.bundleIdentifier ?? ""
        let appName = frontApp?.localizedName ?? "系统"
        
        // Excluded applications check (exact bundle-id match to avoid substring false positives)
        if AppSettings.shared.excludedApps.contains(where: { bundleId.lowercased() == $0.lowercased() }) {
            return
        }
        
        // Terminal applications that perform automatic copy-on-select
        let terminalApps = [
            "com.mitchellh.ghostty",
            "com.googlecode.iterm2",
            "com.apple.Terminal",
            "io.alacritty",
            "dev.warp.Warp-Stable",
            "net.kovidgoyal.kitty"
        ]
        
        // When selection copy is disabled, ignore terminal swipe-to-copy unless Command+C was pressed
        if !AppSettings.shared.enableSelectionCopy {
            let isTerminal = terminalApps.contains(where: { bundleId.localizedCaseInsensitiveContains($0) })
            if isTerminal {
                let timeSinceCmdC = Date().timeIntervalSince(lastExplicitCopyTime)
                if timeSinceCmdC > 1.2 {
                    // Automatic swipe selection without Command+C; ignore!
                    return
                }
            }
        }
        
        processCurrentPasteboard(sourceAppName: appName, sourceBundleId: bundleId)
    }
    
    private func processCurrentPasteboard(sourceAppName: String, sourceBundleId: String) {
        // 1. Check for File URLs first
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [
            NSPasteboard.ReadingOptionKey.urlReadingFileURLsOnly: true
        ]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path }
            
            // If it is a single image file (common in WeChat, Finder, etc.), ingest asynchronously as .image
            let imageExtensions = ["png", "jpg", "jpeg", "webp", "gif", "tiff", "tif", "heic", "heif", "svg", "bmp"]
            if paths.count == 1,
               let first = paths.first,
               imageExtensions.contains((first as NSString).pathExtension.lowercased()) {
                StorageManager.shared.ingestImageFileAsync(
                    path: first,
                    paths: paths,
                    sourceAppName: sourceAppName,
                    sourceBundleId: sourceBundleId
                )
                return
            }
            
            let item = ClipItem(
                type: .file,
                filePaths: paths,
                sourceAppName: sourceAppName,
                sourceAppBundleId: sourceBundleId
            )
            StorageManager.shared.addClip(item)
            return
        }
        
        // 2. Check for Images (read raw Data on main, decode/hash/write on background queue)
        if let types = pasteboard.types,
           types.contains(.png) || types.contains(.tiff) {
            let rawPNG = pasteboard.data(forType: .png)
            let rawTIFF = rawPNG == nil ? pasteboard.data(forType: .tiff) : nil
            if rawPNG != nil || rawTIFF != nil {
                StorageManager.shared.ingestImageDataAsync(
                    rawPNG: rawPNG,
                    rawTIFF: rawTIFF,
                    filePaths: nil,
                    sourceAppName: sourceAppName,
                    sourceBundleId: sourceBundleId
                )
                return
            }
        }
        
        // 3. Check for Strings
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let html = pasteboard.string(forType: .html)
            
            // Check if it is a Color code
            if let colorHex = Self.extractColorHex(from: trimmed) {
                let item = ClipItem(
                    type: .color,
                    plainText: trimmed,
                    htmlText: html,
                    colorHex: colorHex,
                    sourceAppName: sourceAppName,
                    sourceAppBundleId: sourceBundleId
                )
                StorageManager.shared.addClip(item)
                return
            }
            
            // Check if it is a Web URL
            if isValidWebURL(trimmed) {
                let item = ClipItem(
                    type: .url,
                    plainText: trimmed,
                    htmlText: html,
                    sourceAppName: sourceAppName,
                    sourceAppBundleId: sourceBundleId
                )
                StorageManager.shared.addClip(item)
                return
            }
            
            // Regular Text
            let item = ClipItem(
                type: .text,
                plainText: string,
                htmlText: html,
                sourceAppName: sourceAppName,
                sourceAppBundleId: sourceBundleId
            )
            StorageManager.shared.addClip(item)
        }
    }
    
    // Extract normalized #RRGGBB / #RRGGBBAA / #RGB hex color (strict # prefix for hex; supports rgb/rgba/hsl/hsla/oklch)
    nonisolated public static func extractColorHex(from text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        // 1. Hex color: MUST start with '#' to avoid matching numeric codes, dates, or git hashes
        let hexRegex = "^#([A-Fa-f0-9]{3}|[A-Fa-f0-9]{4}|[A-Fa-f0-9]{6}|[A-Fa-f0-9]{8})$"
        if trimmed.range(of: hexRegex, options: .regularExpression) != nil {
            let digits = String(trimmed.dropFirst()).uppercased()
            if digits.count == 4 {
                let expanded = digits.map { "\($0)\($0)" }.joined()
                return "#\(expanded)"
            }
            return "#\(digits)"
        }

        // 2. rgb(...) / rgba(...)
        if let inner = matchFunctionBody(trimmed, prefixRegex: "^rgba?\\(\\s*(.+?)\\s*\\)$") {
            return parseRGBColor(inner)
        }

        // 3. hsl(...) / hsla(...)
        if let inner = matchFunctionBody(trimmed, prefixRegex: "^hsla?\\(\\s*(.+?)\\s*\\)$") {
            return parseHSLColor(inner)
        }

        // 4. oklch(...)
        if let inner = matchFunctionBody(trimmed, prefixRegex: "^oklch\\(\\s*(.+?)\\s*\\)$") {
            return parseOKLCHColor(inner)
        }

        return nil
    }

    nonisolated private static func matchFunctionBody(_ text: String, prefixRegex: String) -> String? {
        guard let regex = try? NSRegularExpression(pattern: prefixRegex, options: .caseInsensitive) else {
            return nil
        }
        let ns = text as NSString
        guard let match = regex.firstMatch(in: text, options: [], range: NSRange(location: 0, length: ns.length)),
              match.numberOfRanges >= 2 else {
            return nil
        }
        return ns.substring(with: match.range(at: 1))
    }

    nonisolated private static func splitColorArgs(_ inner: String) -> (channels: [String], alpha: String?)? {
        if inner.contains(",") {
            guard !inner.contains("/") else { return nil }
            let parts = inner.split(separator: ",", omittingEmptySubsequences: false)
                .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            guard (parts.count == 3 || parts.count == 4), parts.allSatisfy({ !$0.isEmpty }) else {
                return nil
            }
            return (Array(parts.prefix(3)), parts.count == 4 ? parts[3] : nil)
        }

        let slashParts = inner.split(separator: "/", omittingEmptySubsequences: false)
        guard slashParts.count == 1 || slashParts.count == 2 else { return nil }
        let colorTokens = slashParts[0].split(whereSeparator: { $0.isWhitespace }).map(String.init)
        guard colorTokens.count == 3 else { return nil }

        let alphaToken: String?
        if slashParts.count == 2 {
            let trimmedAlpha = slashParts[1].trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmedAlpha.isEmpty else { return nil }
            alphaToken = trimmedAlpha
        } else {
            alphaToken = nil
        }
        return (colorTokens, alphaToken)
    }

    nonisolated private static func parseAlpha(_ token: String?) -> Double? {
        guard let token = token else { return 1.0 }
        if token.hasSuffix("%") {
            guard let pct = Double(String(token.dropLast())), pct >= 0, pct <= 100 else { return nil }
            return pct / 100.0
        }
        guard let val = Double(token), val >= 0, val <= 1 else { return nil }
        return val
    }

    nonisolated private static func parseRGBChannel(_ token: String) -> Int? {
        if token.hasSuffix("%") {
            guard let pct = Double(String(token.dropLast())), pct >= 0, pct <= 100 else { return nil }
            return Int(((pct / 100.0) * 255.0).rounded())
        }
        guard let val = Double(token), val >= 0, val <= 255 else { return nil }
        return Int(val.rounded())
    }

    nonisolated private static func parseHueDegrees(_ token: String) -> Double? {
        let lower = token.lowercased()
        let rawDeg: Double?
        if lower.hasSuffix("deg") {
            rawDeg = Double(String(lower.dropLast(3)))
        } else if lower.hasSuffix("rad") {
            rawDeg = Double(String(lower.dropLast(3))).map { $0 * 180.0 / Double.pi }
        } else if lower.hasSuffix("turn") {
            rawDeg = Double(String(lower.dropLast(4))).map { $0 * 360.0 }
        } else if lower.hasSuffix("grad") {
            rawDeg = Double(String(lower.dropLast(4))).map { $0 * 0.9 }
        } else {
            rawDeg = Double(lower)
        }
        guard let deg = rawDeg, deg.isFinite else { return nil }
        let mod = deg.truncatingRemainder(dividingBy: 360.0)
        return mod < 0 ? mod + 360.0 : mod
    }

    nonisolated private static func formatHex(r: Int, g: Int, b: Int, alpha: Double) -> String {
        let cr = min(max(r, 0), 255)
        let cg = min(max(g, 0), 255)
        let cb = min(max(b, 0), 255)
        if alpha >= 0.9999 {
            return String(format: "#%02X%02X%02X", cr, cg, cb)
        }
        let ca = min(max(Int((alpha * 255.0).rounded()), 0), 255)
        return String(format: "#%02X%02X%02X%02X", cr, cg, cb, ca)
    }

    nonisolated private static func parseRGBColor(_ inner: String) -> String? {
        guard let parsed = splitColorArgs(inner),
              let r = parseRGBChannel(parsed.channels[0]),
              let g = parseRGBChannel(parsed.channels[1]),
              let b = parseRGBChannel(parsed.channels[2]),
              let a = parseAlpha(parsed.alpha) else {
            return nil
        }
        return formatHex(r: r, g: g, b: b, alpha: a)
    }

    nonisolated private static func parseHSLColor(_ inner: String) -> String? {
        guard let parsed = splitColorArgs(inner),
              let h = parseHueDegrees(parsed.channels[0]),
              parsed.channels[1].hasSuffix("%"),
              parsed.channels[2].hasSuffix("%"),
              let sPct = Double(String(parsed.channels[1].dropLast())), sPct >= 0, sPct <= 100,
              let lPct = Double(String(parsed.channels[2].dropLast())), lPct >= 0, lPct <= 100,
              let a = parseAlpha(parsed.alpha) else {
            return nil
        }
        let s = sPct / 100.0
        let l = lPct / 100.0
        let c = (1.0 - abs(2.0 * l - 1.0)) * s
        let x = c * (1.0 - abs((h / 60.0).truncatingRemainder(dividingBy: 2.0) - 1.0))
        let m = l - c / 2.0

        let (r1, g1, b1): (Double, Double, Double)
        switch h {
        case 0..<60: (r1, g1, b1) = (c, x, 0)
        case 60..<120: (r1, g1, b1) = (x, c, 0)
        case 120..<180: (r1, g1, b1) = (0, c, x)
        case 180..<240: (r1, g1, b1) = (0, x, c)
        case 240..<300: (r1, g1, b1) = (x, 0, c)
        default: (r1, g1, b1) = (c, 0, x)
        }

        let r = Int(((r1 + m) * 255.0).rounded())
        let g = Int(((g1 + m) * 255.0).rounded())
        let b = Int(((b1 + m) * 255.0).rounded())
        return formatHex(r: r, g: g, b: b, alpha: a)
    }

    nonisolated private static func parseOKLCHColor(_ inner: String) -> String? {
        guard !inner.contains(","),
              let parsed = splitColorArgs(inner),
              let hDeg = parseHueDegrees(parsed.channels[2]),
              let a = parseAlpha(parsed.alpha) else {
            return nil
        }

        let lToken = parsed.channels[0]
        let lVal: Double
        if lToken.hasSuffix("%") {
            guard let pct = Double(String(lToken.dropLast())), pct >= 0, pct <= 100 else { return nil }
            lVal = pct / 100.0
        } else {
            guard let val = Double(lToken), val >= 0, val <= 1 else { return nil }
            lVal = val
        }

        let cToken = parsed.channels[1]
        let cVal: Double
        if cToken.hasSuffix("%") {
            guard let pct = Double(String(cToken.dropLast())), pct >= 0 else { return nil }
            cVal = (pct / 100.0) * 0.4
        } else {
            guard let val = Double(cToken), val >= 0 else { return nil }
            cVal = val
        }

        let hRad = hDeg * Double.pi / 180.0
        let aLab = cVal * cos(hRad)
        let bLab = cVal * sin(hRad)

        let l_ = lVal + 0.3963377774 * aLab + 0.2158037573 * bLab
        let m_ = lVal - 0.1055613458 * aLab - 0.0638541728 * bLab
        let s_ = lVal - 0.0894841775 * aLab - 1.2914855480 * bLab

        let l3 = l_ * l_ * l_
        let m3 = m_ * m_ * m_
        let s3 = s_ * s_ * s_

        let rLin = +4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3
        let gLin = -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3
        let bLin = -0.0041960863 * l3 - 0.7034186147 * m3 + 1.7076147010 * s3

        func linearToSRGB(_ c: Double) -> Double {
            let clamped = min(max(c, 0.0), 1.0)
            return clamped <= 0.0031308
                ? 12.92 * clamped
                : 1.055 * pow(clamped, 1.0 / 2.4) - 0.055
        }

        let r = Int((linearToSRGB(rLin) * 255.0).rounded())
        let g = Int((linearToSRGB(gLin) * 255.0).rounded())
        let b = Int((linearToSRGB(bLin) * 255.0).rounded())
        return formatHex(r: r, g: g, b: b, alpha: a)
    }
    
    // Check if string is a valid web URL
    private func isValidWebURL(_ string: String) -> Bool {
        guard !string.contains("\n") && !string.contains(" ") else { return false }
        if let url = URL(string: string), let scheme = url.scheme?.lowercased() {
            if (scheme == "http" || scheme == "https") && url.host != nil && !url.host!.isEmpty {
                return true
            }
        }
        return false
    }
}
